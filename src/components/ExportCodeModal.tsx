"use client";

import React, { useState } from "react";
import { useNexusStore } from "../store/useNexusStore";
import { Check, Copy, X, Code2 } from "lucide-react";

export default function ExportCodeModal() {
  const { lang, nodes, edges, isExportModalOpen, setExportModalOpen } =
    useNexusStore();
  const [copied, setCopied] = useState(false);

  if (!isExportModalOpen) return null;

  // تولید فایل Docker Compose واقعی با ایمیج‌های استاندارد Docker Hub و وابستگی‌های گراف (depends_on)
  const dockerComposeCode = [
    "version: '3.9'",
    "# Production-Ready Docker Compose Manifest — Generated by NexusCanvas",
    "services:",
    ...nodes.map((n) => {
      const svcKey = n.id.replace(/[^a-z0-9]+/gi, "-").toLowerCase();
      const deps = edges
        .filter((e) => e.from === n.id)
        .map((e) => e.to.replace(/[^a-z0-9]+/gi, "-").toLowerCase());
      const depBlock =
        deps.length > 0
          ? `\n    depends_on:\n${deps.map((d) => `      - ${d}`).join("\n")}`
          : "";

      return [
        `  ${svcKey}:`,
        `    image: ${n.dockerImage}`,
        `    container_name: ${svcKey}`,
        `    ports:`,
        `      - "${n.port}:${n.port}"`,
        `    deploy:`,
        `      replicas: ${n.replicas}`,
        `      resources:`,
        `        limits:`,
        `          cpus: "${(n.cpuLoad / 50).toFixed(2)}"`,
        `    networks:`,
        `      - nexus-mesh${depBlock}`,
      ].join("\n");
    }),
    "",
    "networks:",
    "  nexus-mesh:",
    "    driver: bridge",
  ].join("\n");

  const handleCopy = () => {
    navigator.clipboard.writeText(dockerComposeCode);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/75 backdrop-blur-md">
      <div
        dir={lang === "fa" ? "rtl" : "ltr"}
        className="w-full max-w-2xl nexus-card rounded-2xl border border-cyan-400/40 p-5 space-y-4"
      >
        <div className="flex items-center justify-between border-b border-white/10 pb-3">
          <div className="flex items-center gap-2">
            <Code2 className="w-5 h-5 text-cyan-400" />
            <h3 className="text-sm font-bold text-white">
              {lang === "fa"
                ? "خروجی استاندارد Docker Compose با ایمیج‌های واقعی و depends_on"
                : "Valid Docker Compose Manifest (Real Official Images & depends_on)"}
            </h3>
          </div>
          <button
            onClick={() => setExportModalOpen(false)}
            className="btn-nexus p-1.5 rounded-lg"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        <pre
          dir="ltr"
          className="p-4 rounded-xl bg-[#02040A] border border-white/10 font-mono text-xs text-emerald-300 overflow-x-auto max-h-[340px]"
        >
          {dockerComposeCode}
        </pre>

        <div className="flex justify-end gap-2">
          <button
            onClick={handleCopy}
            className="btn-nexus-emerald px-4 py-2 rounded-xl font-mono text-xs font-bold flex items-center gap-1.5"
          >
            {copied ? (
              <>
                <Check className="w-4 h-4" />
                <span>Copied to Clipboard!</span>
              </>
            ) : (
              <>
                <Copy className="w-4 h-4" />
                <span>Copy docker-compose.yml</span>
              </>
            )}
          </button>
        </div>
      </div>
    </div>
  );
}